"""Writes src/text/unicode_tables.inc: code point ranges of Unicode letters (L*) and numbers (N*).

    python3 tools/gen_unicode_tables.py > src/text/unicode_tables.inc
"""
import sys
import unicodedata


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        hit = pred(cp)
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit(name, rs):
    print(f"constexpr CodepointRange {name}[] = {{")
    for i in range(0, len(rs), 4):
        print("    " + " ".join(f"{{0x{a:06X}, 0x{b:06X}}}," for a, b in rs[i:i + 4]))
    print("};")


print(f"// Generated by tools/gen_unicode_tables.py from Unicode {unicodedata.unidata_version}. Do not edit.")
emit("kLetterRanges", ranges(lambda c: unicodedata.category(chr(c)).startswith("L")))
emit("kNumberRanges", ranges(lambda c: unicodedata.category(chr(c)).startswith("N")))
